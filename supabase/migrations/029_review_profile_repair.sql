begin;
create table if not exists public.player_reviews(id uuid primary key default gen_random_uuid(),user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,game_id uuid not null references public.games(id) on delete cascade,body text not null check(char_length(body) between 20 and 3000),status text not null default 'pending' check(status in ('pending','approved','rejected')),created_at timestamptz not null default now(),unique(user_id,game_id));
alter table public.player_reviews enable row level security;
drop policy if exists player_review_public on public.player_reviews;
create policy player_review_public on public.player_reviews for select using(status='approved');
drop policy if exists player_review_owner on public.player_reviews;
create policy player_review_owner on public.player_reviews for select to authenticated using(user_id=auth.uid());
drop policy if exists player_review_submit on public.player_reviews;
create policy player_review_submit on public.player_reviews for insert to authenticated with check(user_id=auth.uid() and status='pending');
drop policy if exists player_review_delete on public.player_reviews;
create policy player_review_delete on public.player_reviews for delete to authenticated using(user_id=auth.uid());
drop policy if exists player_review_staff_read on public.player_reviews;
create policy player_review_staff_read on public.player_reviews for select to authenticated using(public.has_staff_role(array['admin','moderator']));
drop policy if exists player_review_staff_update on public.player_reviews;
create policy player_review_staff_update on public.player_reviews for update to authenticated using(public.has_staff_role(array['admin','moderator'])) with check(public.has_staff_role(array['admin','moderator']));
grant select on public.player_reviews to anon,authenticated;
grant insert,delete on public.player_reviews to authenticated;
grant update(status) on public.player_reviews to authenticated;
create index if not exists player_reviews_profile_idx on public.player_reviews(user_id,created_at desc) where status='approved';
create index if not exists player_reviews_game_status_idx on public.player_reviews(game_id,status,created_at desc);
create index if not exists player_reviews_queue_idx on public.player_reviews(status,created_at);
notify pgrst,'reload schema';
commit;
